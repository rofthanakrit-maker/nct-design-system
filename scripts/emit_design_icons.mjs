const iconDir = path.join(outDir, "components/icons");
fs.mkdirSync(iconDir, { recursive: true });
fs.writeFileSync(path.join(iconDir, "Icon.jsx"), jsx);
fs.writeFileSync(path.join(iconDir, "Icon.d.ts"), dts);
fs.writeFileSync(path.join(iconDir, "Icon.prompt.md"), prompt);
fs.writeFileSync(path.join(iconDir, "card.html"), card);

// ---- self-check: load Icon.jsx the way the bundle does (React as a global binding,
// import line and export keyword stripped), render every glyph, then compare each
// against the lucide-react component @nct/slides ships
const require = createRequire(path.join(repo, "web/package.json"));
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const body = jsx.replace(/^import React from "react";\n/, "").replace(/^export function/m, "function");
const Icon = Function("React", `${body}\nreturn Icon;`)(React);
const lucideReact = require("lucide-react");
const inner = (html) => html.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");

for (const name of NAMES) {
  const ours = renderToStaticMarkup(React.createElement(Icon, { icon: name, size: "body", tone: "accent" }));
  if (!/^<svg[^>]*viewBox="0 0 24 24"/.test(ours)) fail(`${name} did not render an svg`);
  if (typeof lucideReact[name] !== "object" && typeof lucideReact[name] !== "function") fail(`lucide-react has no export ${name}`);
  if (inner(ours) !== inner(renderToStaticMarkup(React.createElement(lucideReact[name])))) fail(`${name} differs from lucide-react's own glyph`);
}
const labelled = renderToStaticMarkup(React.createElement(Icon, { icon: NAMES[0], label: "ป้าย" }));
if (!labelled.includes('role="img"') || !labelled.includes('aria-label="ป้าย"')) fail("label did not reach the svg");
const warn = console.warn;
let warned = false;
console.warn = () => { warned = true; };
const unknown = renderToStaticMarkup(React.createElement(Icon, { icon: "NotAGlyph" }));
console.warn = warn;
if (unknown !== "" || !warned) fail("an unknown glyph should render nothing and warn");

console.log(`${NAMES.length} glyphs from web/src/index.ts, lucide-react ${lucideVersion}`);
console.log(`wrote ${iconDir}: Icon.jsx (${jsx.length} bytes), Icon.d.ts, Icon.prompt.md, card.html (760x${cardHeight})`);
console.log("every glyph matches lucide-react's own render; label and unknown-name checks pass");
